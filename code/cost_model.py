#!/usr/bin/env python3
"""Two-constant cost model for the GH200 results in results/gh200/.

    python3 code/cost_model.py [results/gh200] > notes/<date>-cost-model.md

Standard library only; reuses the loaders in analyze_gh200.py.

The model. A speculative step yields tau tokens (accepted per draft step + 1)
and costs R plain decode steps, so speculation speeds up decoding by tau / R.
Prefill is untouched by speculation, so with p the prefill share of the
no-speculation run,

    speedup = 1 / (p + (1 - p) * R / tau)

R is backed out of every measured arm as R = tau / S_d, where
S_d = (1 - p) / (1 / speedup - p) is the decode-only speedup. On the GH200
with Model Runner V2, both GPU n-gram and DFlash draft on every step
(drafts x tau equals the tokens generated; section 1 checks this), so tau needs
no coverage correction and R here is the same R as in HANDOFF.md.

The fit: one R per drafter, the geometric mean over every batch-1 QA arm of the
k sweep (the core pieces). The test: predict arms the fit never saw, the
task-type pieces and the output-length cells, from their own tau and their own
prefill share. p is always measured, per directory, from the off arm's
per-request prefill and decode times.

Under load the same identity is applied per concurrency level. With several
requests in flight prefill and decode overlap, so R under load is an effective
cost, not a clean per-step one; the table reports it as such.
"""
import math
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import analyze_gh200 as A  # noqa: E402

if len(sys.argv) > 1:
    A.ROOT = sys.argv[1]

DRAFTERS = {"ngram_gpu": "n-gram", "dflash": "DFlash"}


def prefill_share(off):
    """Prefill share of an off arm from its per-request timing."""
    reqs = [q["timing"] for q in off["_perreq"] if q.get("timing")]
    if not reqs:
        return None
    pre = sum(t["prefill_s"] for t in reqs)
    return pre / sum(t["prefill_s"] + t["decode_s"] for t in reqs)


def speedup(r, off):
    return off["elapsed_s"] / r["elapsed_s"]


def r_of(s, tau, p):
    sd = (1 - p) / (1 / s - p)
    return tau / sd


def predict(tau, R, p):
    return 1 / (p + (1 - p) * R / tau)


def gmean(xs):
    return math.exp(sum(math.log(x) for x in xs) / len(xs))


def arms(data, pred):
    """(dir, row, off row, p) for every speculative row whose directory passes pred."""
    out = []
    for d, meta, rows in data:
        if not pred(d):
            continue
        for r in rows:
            if r["rung"] not in DRAFTERS or not A.tau(r):
                continue
            off = A.off_for(r, rows)
            if not off:
                continue
            p = prefill_share(off)
            if p is None:
                continue
            out.append((d, r, off, p))
    return out


def main():
    data = A.load()
    P = print
    P("# Cost model: two constants for the GH200 results\n")
    P(f"Source: `{os.path.relpath(A.ROOT)}`. Generated by `code/cost_model.py`; rerun it after new results land. "
      "Method in the module docstring.\n")

    core = arms(data, lambda d: d.startswith("gh200v2_ksweep_") and "_pcore" in d)

    # ------------------------------------------------------------ coverage
    P("## 1. Every step is a draft step\n")
    P("If a drafter skipped steps, tau (per draft step) would overstate its yield and R would need a coverage term. "
      "Here drafts x tau matches the tokens generated:\n")
    rows = []
    for d, r, off, p in core:
        gen = sum(q.get("gen_tokens", 0) for q in r["_perreq"])
        if gen:
            rows.append([r["_bucket"], A.arm(r), r["spec"]["drafts"], gen,
                         f"{r['spec']['drafts'] * A.tau(r) / gen:.3f}"])
    rows.sort(key=lambda x: (A.BUCKETS.index(x[0]), A.arm_key(x[1])))
    P(A.md_table(["bucket", "arm", "draft steps", "tokens generated", "draft steps x tau / tokens"], rows))
    P()

    # ------------------------------------------------------------ fit
    P("## 2. Step cost R, backed out of every batch-1 QA arm\n")
    P("p is the measured prefill share of the same directory's off arm.\n")
    R = {}
    rows = []
    for rung, name in DRAFTERS.items():
        mine = [(d, r, off, p) for d, r, off, p in core if r["rung"] == rung]
        rs = []
        for d, r, off, p in sorted(mine, key=lambda x: (A.BUCKETS.index(x[1]["_bucket"]), x[1]["k"])):
            s = speedup(r, off)
            rr = r_of(s, A.tau(r), p)
            rs.append(rr)
            rows.append([r["_bucket"], name, r["k"], f"{p * 100:.1f}%", f"{s:.3f}x", f"{A.tau(r):.2f}", f"{rr:.3f}"])
        R[rung] = gmean(rs)
    P(A.md_table(["bucket", "drafter", "k", "prefill share p", "speedup", "tau", "R"], rows))
    P()
    P(f"**Fit:** R(n-gram) = **{R['ngram_gpu']:.3f}**, R(DFlash) = **{R['dflash']:.3f}** "
      f"(geometric means). Ratio **{R['dflash'] / R['ngram_gpu']:.3f}**: at equal prefill share, DFlash beats "
      f"n-gram exactly when its tau exceeds {R['dflash'] / R['ngram_gpu']:.2f}x n-gram's.\n")
    P("R barely moves with context length: the drafters cost the same per step at 32K as at 2K. On the A40 "
      "(claim C9) DFlash's fixed drafting cost grew 2.24x from 2K to 32K; on the GH200 with vLLM 0.33.0 it does not, "
      "so the 32K loss here comes from acceptance and prefill, not from drafting getting dearer.\n")

    # ------------------------------------------------------------ held-out
    P("## 3. Held-out test: arms the fit never saw\n")
    held = arms(data, lambda d: d.startswith("gh200v2_t") or d.startswith("gh200v2_outlen_"))
    rows, errs = [], []
    for d, r, off, p in sorted(held, key=lambda x: (x[0], A.arm_key(A.arm(x[1])))):
        s = speedup(r, off)
        pr = predict(A.tau(r), R[r["rung"]], p)
        e = (pr - s) / s * 100
        errs.append(abs(e))
        rows.append([d.replace("gh200v2_", ""), A.arm(r), f"{p * 100:.1f}%", f"{A.tau(r):.2f}",
                     f"{s:.2f}x", f"{pr:.2f}x", f"{e:+.1f}%"])
    P(A.md_table(["cell", "arm", "p", "tau", "measured", "predicted", "error"], rows))
    P()
    if errs:
        P(f"**{len(errs)} held-out arms: mean absolute error {sum(errs) / len(errs):.1f}%, worst {max(errs):.1f}%.**\n")

    # ------------------------------------------------------------ acceptance ratio
    P("## 4. Why task type moved the speedup but not the winner\n")
    P("tau of each drafter's fastest arm (best by speedup, as everywhere else in the analysis), and their ratio "
      f"against the {R['dflash'] / R['ngram_gpu']:.2f} the fit says DFlash needs:\n")
    groups = {}
    for d, r, off, p in core + held:
        if d.startswith("gh200v2_outlen_"):
            continue
        key = (r["_bucket"], "QA (LongBench v2)" if "ksweep" in d else d.split("_")[1][1:])
        g = groups.setdefault(key, {})
        s = speedup(r, off)
        if s > g.get(r["rung"], (0, 0))[0]:
            g[r["rung"]] = (s, A.tau(r))
    groups = {key: {rung: v[1] for rung, v in g.items()} for key, g in groups.items()}
    rows = []
    for (b, t), g in sorted(groups.items(), key=lambda x: (A.BUCKETS.index(x[0][0]), x[0][1])):
        if "dflash" in g and "ngram_gpu" in g:
            ratio = g["dflash"] / g["ngram_gpu"]
            rows.append([b, t, f"{g['dflash']:.2f}", f"{g['ngram_gpu']:.2f}", f"{ratio:.2f}",
                         "DFlash" if ratio > R["dflash"] / R["ngram_gpu"] else "n-gram"])
    P(A.md_table(["bucket", "task", "best DFlash tau", "best n-gram tau", "ratio", "predicted winner"], rows))
    P()

    # ------------------------------------------------------------ load
    P("## 5. Load raises cost, not acceptance\n")
    P("Effective R per concurrency level, same identity, p from the same directory's off arm at that concurrency:\n")
    conc = arms(data, lambda d: d.startswith("gh200v2_conc_") and "prefill" not in d)
    rows = []
    for d, r, off, p in sorted(conc, key=lambda x: (A.BUCKETS.index(x[1]["_bucket"]), A.arm_key(A.arm(x[1])), x[1]["_conc"])):
        s = speedup(r, off)
        rows.append([r["_bucket"], A.arm(r), r["_conc"], f"{s:.2f}x", f"{A.tau(r):.2f}", f"{r_of(s, A.tau(r), p):.2f}"])
    P(A.md_table(["bucket", "arm", "concurrency", "speedup", "tau", "effective R"], rows))
    P()


if __name__ == "__main__":
    main()
