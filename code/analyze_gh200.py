#!/usr/bin/env python3
"""Tables from the DeltaAI GH200 results in results/gh200/ (dtai2 bundles and pieces).

    python3 code/analyze_gh200.py [results/gh200] > notes/<date>-gh200-results.md

Standard library only. Reads every gh200v2_* directory, original or piece
(gh200v2_<cell>_<bucket>[_p<tag>]), and joins every speculative arm to the off
arm of its own directory, so every speedup divides by an off arm timed in the
same job on the same GPU. A directory without an off arm (the three acc pieces,
whose off arm vLLM 0.33.0 refused: per-request acceptance needs a drafter)
borrows the core off arms of its bucket, and the table says so.

Speedup = off elapsed / arm elapsed for the same prompts. tau = accepted tokens
per draft step + 1, the tokens a verify step yields.
"""
import collections
import json
import os
import re
import statistics as st
import sys

ROOT = sys.argv[1] if len(sys.argv) > 1 else os.path.join(os.path.dirname(__file__), "..", "results", "gh200")
BUCKETS = ["2K", "8K", "32K"]
DIR_RE = re.compile(r"^gh200v2_(?P<cell>[a-zA-Z0-9]+(?:_prefill)?)_(?P<bucket>2K|8K|32K)(?:_p(?P<piece>[A-Za-z0-9]+))?$")


def load():
    out = []
    for d in sorted(os.listdir(ROOT)):
        p = os.path.join(ROOT, d, "results.jsonl")
        if not os.path.isfile(p):
            continue
        rows = [json.loads(l) for l in open(p) if l.strip()]
        m = DIR_RE.match(d)
        meta = m.groupdict() if m else {"cell": d.replace("gh200v2_", ""), "bucket": None, "piece": None}
        for r in rows:
            pr = os.path.join(ROOT, d, r.get("perreq", ""))
            r["_perreq"] = json.load(open(pr)) if r.get("perreq") and os.path.isfile(pr) else []
            r["_dir"] = d
            r["_cell"], r["_bucket"], r["_piece"] = meta["cell"], meta["bucket"] or r.get("bucket"), meta["piece"]
            r["_conc"] = r.get("max_num_seqs") or (r.get("resolved") or {}).get("max_num_seqs") or 1
        out.append((d, meta, rows))
    return out


def svc(t):
    """Service time of one request: prefill plus decode. The engine's engine_s
    also counts the time the request waited in the queue behind earlier ones,
    which at c=1 grows down the list, so it is not used for per-prompt ratios."""
    return t["prefill_s"] + t["decode_s"]


def arm(r):
    return "off" if r["rung"] == "off" else f"{r['rung']} k={r['k']}"


def tau(r):
    s = r.get("spec") or {}
    return (s.get("accepted_tokens", 0) / s["drafts"] + 1) if s.get("drafts") else None


def fmt(x, nd=2, suf=""):
    return "-" if x is None else f"{x:.{nd}f}{suf}"


def md_table(head, rows):
    lines = ["| " + " | ".join(head) + " |", "|" + "|".join("---" for _ in head) + "|"]
    lines += ["| " + " | ".join(str(c) for c in row) + " |" for row in rows]
    return "\n".join(lines)


def arm_key(a):
    if a == "off":
        return (0, 0)
    rung, k = a.split(" k=")
    return ({"ngram_gpu": 1, "ngram": 1, "dflash": 2}.get(rung, 3), int(k))


def off_for(r, rows):
    """The off arm of the same directory at the same concurrency."""
    o = [x for x in rows if x["rung"] == "off" and x["_conc"] == r["_conc"]]
    return o[0] if o else None


def main():
    data = load()
    allrows = [r for _, _, rows in data for r in rows]
    P = print

    P("# GH200 results: dtai2 bundles and pieces\n")
    P(f"Source: `{os.path.relpath(ROOT)}`, {len(data)} directories, {len(allrows)} rows. "
      "Generated by `code/analyze_gh200.py`; rerun it after new results land.\n")

    # ---------------------------------------------------------------- integrity
    P("## 1. Integrity\n")
    issues = []
    for d, meta, rows in data:
        if not rows:
            issues.append(f"`{d}`: no rows")
        ids = collections.Counter(r["run_id"] for r in rows)
        for k, v in ids.items():
            if v > 1:
                issues.append(f"`{d}`: run `{k}` appears {v} times")
        for r in rows:
            res = r.get("resolved") or {}
            if res.get("use_v2_model_runner") is not True:
                issues.append(f"`{d}` `{r['run_id']}`: not on Model Runner V2")
            if (r.get("warmup") or {}).get("measured_too"):
                issues.append(f"`{d}` `{r['run_id']}`: warm-up prompts also measured")
            if r.get("per_request_engine_timing") not in (None, r["limit"]) and not r.get("loop_timing"):
                issues.append(f"`{d}` `{r['run_id']}`: engine timing on {r.get('per_request_engine_timing')} of {r['limit']}")
        asyncs = {(r.get("resolved") or {}).get("async_scheduling") for r in rows}
        if len(asyncs) > 1:
            issues.append(f"`{d}`: arms differ in async scheduling {asyncs}")
        if meta.get("cell") not in ("nsys",) and rows and not any(r["rung"] == "off" for r in rows):
            issues.append(f"`{d}`: no off arm (borrows its bucket's core off arms below)")
    harn = collections.Counter(r.get("harness") or "?" for r in allrows)
    P(f"- Harness versions: {', '.join(f'`{k}` ({v} rows)' for k, v in sorted(harn.items()))}.")
    P(f"- Model Runner V2 on {sum(1 for r in allrows if (r.get('resolved') or {}).get('use_v2_model_runner') is True)} of {len(allrows)} rows; "
      f"async scheduling {sorted({str((r.get('resolved') or {}).get('async_scheduling')) for r in allrows})}.")
    P("- Findings:" if issues else "- No integrity problems found.")
    for i in issues:
        P(f"  - {i}")

    # Determinism: off outputs across every off arm at c=1 and 256 tokens, per bucket.
    P("\n**Determinism and losslessness at c=1, 256 tokens.** For each prompt, the sha1 of its output "
      "in every off arm, and in every speculative arm, against the most common off output.\n")
    det_rows = []
    for b in BUCKETS:
        offs = [r for r in allrows if r["_bucket"] == b and r["rung"] == "off" and r["_conc"] == 1
                and r.get("max_tokens") == 256 and r["_perreq"] and not r["_dir"].startswith("gh200_")]
        specs = [r for r in allrows if r["_bucket"] == b and r["rung"] != "off" and r["_conc"] == 1
                 and r.get("max_tokens") == 256 and r["_perreq"] and r["_cell"] not in ("nsys",)]
        ref = {}
        for r in offs:
            for q in r["_perreq"]:
                ref.setdefault(q["id"], collections.Counter())[q["sha1"]] += 1
        mode = {i: c.most_common(1)[0][0] for i, c in ref.items()}
        def agree(rs):
            n = s = 0
            for r in rs:
                for q in r["_perreq"]:
                    if q["id"] in mode:
                        n += 1; s += q["sha1"] == mode[q["id"]]
            return s, n
        so, no = agree(offs); ss, ns = agree(specs)
        det_rows.append([b, len(offs), f"{so}/{no}", len(specs), f"{ss}/{ns}" + (f" ({100*ss/ns:.1f}%)" if ns else "")])
    P(md_table(["bucket", "off arms", "off outputs identical", "spec arms", "spec outputs identical to off"], det_rows))
    P("\nBy arm, core pieces (outputs identical to the same piece's off arm, and the first differing token when not):\n")
    la_rows = []
    for d, m, rows in data:
        if m["cell"] != "ksweep":
            continue
        o = off_for({"_conc": 1}, rows)
        if not o:
            continue
        om = {q["id"]: q for q in o["_perreq"]}
        for r in rows:
            if r["rung"] == "off":
                continue
            same, firsts = 0, []
            for q in r["_perreq"]:
                oq = om.get(q["id"])
                if not oq:
                    continue
                if q["sha1"] == oq["sha1"]:
                    same += 1
                elif q.get("token_ids") and oq.get("token_ids"):
                    a_, b_ = q["token_ids"], oq["token_ids"]
                    firsts.append(next((j for j, (x, y) in enumerate(zip(a_, b_)) if x != y), min(len(a_), len(b_))))
            la_rows.append([m["bucket"], arm(r), f"{same}/{len(r['_perreq'])}",
                            f"median {st.median(firsts):.0f}, min {min(firsts)}" if firsts else "-"])
    la_rows.sort(key=lambda x: (BUCKETS.index(x[0]), arm_key(x[1])))
    P(md_table(["bucket", "arm", "identical", "first differing token"], la_rows))

    # ---------------------------------------------------------------- k sweep
    def borrowed_off(b):
        o = [r for r in allrows if r["_cell"] == "ksweep" and r["_bucket"] == b and r["rung"] == "off"]
        return st.mean(x["elapsed_s"] for x in o) if o else None

    P("\n## 2. k sweep at c=1 (core cell)\n")
    P("Each arm against the off arm of its own piece. Off: mean elapsed of the three core pieces' off arms.\n")
    sweep = {}
    for b in BUCKETS:
        rs = [(r, rows) for d, m, rows in data for r in rows if m["cell"] == "ksweep" and m["bucket"] == b]
        for r, rows in rs:
            if r["rung"] == "off":
                continue
            o = off_for(r, rows)
            sweep.setdefault(b, {})[arm(r)] = (o["elapsed_s"] / r["elapsed_s"] if o else None, tau(r), r)
    arms = sorted({a for b in sweep for a in sweep[b]}, key=arm_key)
    P(md_table(["arm"] + [f"{b} speedup" for b in BUCKETS] + [f"{b} tau" for b in BUCKETS],
               [[a] + [fmt(sweep.get(b, {}).get(a, (None,))[0], 2, "x") for b in BUCKETS]
                    + [fmt(sweep.get(b, {}).get(a, (None, None))[1]) for b in BUCKETS] for a in arms]))
    best = []
    for b in BUCKETS:
        if sweep.get(b):
            for rung in ("ngram_gpu", "dflash"):
                c = {a: v for a, v in sweep[b].items() if a.startswith(rung)}
                if c:
                    a, v = max(c.items(), key=lambda kv: kv[1][0] or 0)
                    best.append([b, rung, a.split("=")[1], fmt(v[0], 2, "x"), fmt(v[1])])
    P("\nBest k per length and drafter:\n")
    P(md_table(["bucket", "drafter", "best k", "speedup", "tau"], best))

    # Acceptance by position for DFlash at c=1 (acc cell rows carry it in spec).
    P("\n**DFlash acceptance by draft position at c=1** (from the speculative rows' engine counters; position 1 first):\n")
    pos_rows = []
    for b in BUCKETS:
        for r in sorted((r for r in allrows if r["_bucket"] == b and r["_cell"] == "ksweep" and r["rung"] == "dflash"), key=lambda r: r["k"]):
            ap = (r.get("spec") or {}).get("acceptance_by_position") or (r.get("spec") or {}).get("per_position_acceptance_rate")
            if ap:
                pos_rows.append([b, r["k"], ", ".join(f"{x:.2f}" for x in ap[:8]) + (" ..." if len(ap) > 8 else "")])
    P(md_table(["bucket", "k", "acceptance at positions 1..8"], pos_rows) if pos_rows else "_Not recorded in these rows._")

    # ---------------------------------------------------------------- loopA and rep
    P("\n## 3. Repeatability\n")
    P("Off arm elapsed for the same prompts in every job that ran it at c=1 with 256 output tokens "
      "(core pieces, loopA pieces' batch timing excluded, rep, k0):\n")
    rep_rows = []
    for b in BUCKETS:
        offs = [r for r in allrows if r["_bucket"] == b and r["rung"] == "off" and r["_conc"] == 1 and r.get("max_tokens") == 256
                and not r.get("loop_timing") and r["_cell"] in ("ksweep", "rep", "k0") and r.get("prefix_caching") in (None, True, "default")]
        xs = [r["elapsed_s"] for r in offs]
        if len(xs) > 1:
            rep_rows.append([b, len(xs), f"{min(xs):.1f} to {max(xs):.1f}", f"{100*st.pstdev(xs)/st.mean(xs):.2f}%"])
    P(md_table(["bucket", "off arms", "elapsed range (s)", "spread (sd/mean)"], rep_rows))
    P("\nSame arm in the rep piece against the core piece (each against its own off arm):\n")
    rr = []
    for b in BUCKETS:
        rep = [(r, rows) for d, m, rows in data for r in rows if m["cell"] == "rep" and m["bucket"] == b and r["rung"] != "off"]
        for r, rows in rep:
            o = off_for(r, rows)
            s_rep = o["elapsed_s"] / r["elapsed_s"] if o else None
            s_core = sweep.get(b, {}).get(arm(r), (None,))[0]
            rr.append([b, arm(r), fmt(s_core, 3, "x"), fmt(s_rep, 3, "x"),
                       fmt(100 * (s_rep / s_core - 1), 2, "%") if s_rep and s_core else "-"])
    P(md_table(["bucket", "arm", "core speedup", "rep speedup", "difference"], rr))

    P("\nloopA (each prompt timed alone, outside the batch) against core, per arm, speedup:\n")
    la = []
    for b in BUCKETS:
        for d, m, rows in data:
            if m["cell"] == "loopA" and m["bucket"] == b:
                for r in rows:
                    if r["rung"] == "off":
                        continue
                    o = off_for(r, rows)
                    s = o["elapsed_s"] / r["elapsed_s"] if o else None
                    la.append([b, arm(r), fmt(sweep.get(b, {}).get(arm(r), (None,))[0], 2, "x"), fmt(s, 2, "x")])
    la.sort(key=lambda x: (BUCKETS.index(x[0]), arm_key(x[1])))
    P(md_table(["bucket", "arm", "core", "loopA"], la))

    # ---------------------------------------------------------------- prefill, k0, nopc
    P("\n## 4. Prefill share, idle-drafter cost, prefix caching\n")
    pf = []
    for b in BUCKETS:
        pre = [r for r in allrows if r["_cell"] == "prefill" and r["_bucket"] == b]
        core_off = borrowed_off(b)
        k0 = [r for r in allrows if r["_cell"] == "k0" and r["_bucket"] == b]
        k0o = [r for r in k0 if r["rung"] == "off"]; k0d = [r for r in k0 if r["rung"] == "dflash"]
        pre_off = [r for r in pre if r["rung"] == "off"]
        pre_spec = {arm(r): r["elapsed_s"] for r in pre if r["rung"] != "off"}
        nopc = [(r, rows) for d, m, rows in data for r in rows if m["cell"] == "nopc" and m["bucket"] == b]
        pf.append([b, fmt(pre_off[0]["elapsed_s"], 1) if pre_off else "-", fmt(core_off, 1),
                   fmt(100 * pre_off[0]["elapsed_s"] / core_off, 0, "%") if pre_off and core_off else "-",
                   ", ".join(f"{a} {v:.1f}" for a, v in sorted(pre_spec.items(), key=lambda kv: arm_key(kv[0]))) or "-",
                   fmt(100 * (k0d[0]["elapsed_s"] / k0o[0]["elapsed_s"] - 1), 1, "%") if k0o and k0d else "-"])
    P(md_table(["bucket", "prefill only, off (s)", "full off (s)", "prefill share", "prefill only, spec arms (s)", "idle DFlash (k0) cost"], pf))
    P("\nPer-request split, off arms of the core pieces (median per prompt; share = prefill / (prefill + decode)):\n")
    sp = []
    for b in BUCKETS:
        qs = [q["timing"] for r in allrows if r["_cell"] == "ksweep" and r["_bucket"] == b and r["rung"] == "off" for q in r["_perreq"] if q.get("timing")]
        if qs:
            sp.append([b, len(qs), fmt(st.median(q["prefill_s"] for q in qs), 3), fmt(st.median(q["decode_s"] for q in qs), 3),
                       fmt(100 * st.median(q["prefill_s"] / svc(q) for q in qs), 0, "%")])
    P(md_table(["bucket", "requests", "prefill (s)", "decode (s)", "prefill share"], sp))
    nop = []
    for d, m, rows in data:
        if m["cell"] == "nopc":
            for r in rows:
                if r["rung"] == "off":
                    continue
                o = off_for(r, rows)
                nop.append([m["bucket"], arm(r), fmt(sweep.get(m["bucket"], {}).get(arm(r), (None,))[0], 2, "x"),
                            fmt(o["elapsed_s"] / r["elapsed_s"] if o else None, 2, "x")])
    if nop:
        P("\nPrefix caching off (nopc) against on (core), speedup:\n")
        P(md_table(["bucket", "arm", "caching on", "caching off"], nop))

    # ---------------------------------------------------------------- concurrency
    P("\n## 5. Concurrency\n")
    P("Speedup of each arm against the off arm at the same concurrency in the same piece. "
      "c=1 comes from the conc c1N and c1D pieces (128 prompts at 2K and 8K, 48 at 32K).\n")
    for b in BUCKETS:
        cc = collections.defaultdict(dict)
        offtps = {}
        for d, m, rows in data:
            if m["cell"] == "conc" and m["bucket"] == b:
                for r in rows:
                    c = r["_conc"]
                    if r["rung"] == "off":
                        offtps[c] = r["gen_tokens"] / r["elapsed_s"]
                        continue
                    o = off_for(r, rows)
                    cc[arm(r)][c] = o["elapsed_s"] / r["elapsed_s"] if o else None
        if not cc:
            continue
        cs = sorted({c for a in cc for c in cc[a]})
        P(f"**{b}**\n")
        P(md_table(["arm"] + [f"c={c}" for c in cs],
                   [["off tokens/s"] + [fmt(offtps.get(c), 0) for c in cs]] +
                   [[a] + [fmt(cc[a].get(c), 2, "x") for c in cs] for a in sorted(cc, key=arm_key)]))
        P("")

    # ---------------------------------------------------------------- router by length and concurrency
    P("**Choosing by length and concurrency.** Best arm in each (length, concurrency) cell above, against "
      "the one arm that is best overall (highest geometric mean speedup across all cells), on the arms every "
      "conc cell ran (GPU n-gram k=2, 5; DFlash k=2, 4, 7, 15):\n")
    cells = {}
    for d, m, rows in data:
        if m["cell"] == "conc":
            for r in rows:
                if r["rung"] == "off":
                    continue
                o = off_for(r, rows)
                if o:
                    cells.setdefault((m["bucket"], r["_conc"]), {})[arm(r)] = o["elapsed_s"] / r["elapsed_s"]
    common = set.intersection(*(set(v) for v in cells.values())) if cells else set()
    if common:
        import math
        gm = {a: math.exp(st.mean(math.log(cells[c][a]) for c in cells)) for a in common}
        g = max(gm, key=gm.get)
        rt = []
        for (b, c) in sorted(cells, key=lambda x: (BUCKETS.index(x[0]), x[1])):
            v = {a: cells[(b, c)][a] for a in common}
            ba = max(v, key=v.get)
            rt.append([b, c, ba, fmt(v[ba], 2, "x"), fmt(v[g], 2, "x"), fmt(100 * (v[ba] / v[g] - 1), 1, "%")])
        P(f"Best single arm overall: **{g}** (geometric mean {gm[g]:.2f}x).\n")
        P(md_table(["bucket", "c", "best arm here", "its speedup", f"{g}", "gain from choosing"], rt))
        P("")

    # ---------------------------------------------------------------- per prompt oracle and domains
    P("## 6. Per-prompt headroom for a router (c=1, core pieces)\n")
    P("For each prompt, the ratio of each arm's service time (prefill + decode, queue wait excluded) to the "
      "same prompt's off service time in the same piece. Total time weights prompts by their mean off service time. Oracle: the best arm for "
      "each prompt. Domain router: the best arm per LongBench domain, chosen on the same prompts "
      "(optimistic, no held-out split).\n")
    orc = []
    dom_tab = []
    for b in BUCKETS:
        ratio = collections.defaultdict(dict)    # arm -> id -> ratio
        offt = collections.defaultdict(list)     # id -> off engine times
        doms = {}
        for d, m, rows in data:
            if m["cell"] != "ksweep" or m["bucket"] != b:
                continue
            o = off_for({"_conc": 1}, rows)
            if not o:
                continue
            ot = {q["id"]: svc(q["timing"]) for q in o["_perreq"] if q.get("timing")}
            for i, t in ot.items():
                offt[i].append(t)
            for q in o["_perreq"]:
                doms[q["id"]] = q.get("domain") or "?"
            for r in rows:
                if r["rung"] == "off":
                    continue
                for q in r["_perreq"]:
                    if q.get("timing") and q["id"] in ot:
                        ratio[arm(r)][q["id"]] = svc(q["timing"]) / ot[q["id"]]
        ids = [i for i in offt if all(i in ratio[a] for a in ratio)]
        if not ids or not ratio:
            continue
        w = {i: st.mean(offt[i]) for i in ids}
        tot_off = sum(w.values())
        fixed = {a: sum(w[i] * ratio[a][i] for i in ids) for a in ratio}
        best_a = min(fixed, key=fixed.get)
        oracle = sum(w[i] * min(ratio[a][i] for a in ratio) for i in ids)
        winners = collections.Counter(min(ratio, key=lambda a: ratio[a][i]) for i in ids)
        by_dom = collections.defaultdict(list)
        for i in ids:
            by_dom[doms.get(i, "?")].append(i)
        dom_router = 0.0
        for dname, dids in by_dom.items():
            da = min(ratio, key=lambda a: sum(w[i] * ratio[a][i] for i in dids))
            dom_router += sum(w[i] * ratio[da][i] for i in dids)
            dom_tab.append([b, dname, len(dids), da,
                            fmt(sum(w[i] for i in dids) / sum(w[i] * ratio[da][i] for i in dids), 2, "x"),
                            fmt(sum(w[i] for i in dids) / sum(w[i] * ratio[best_a][i] for i in dids), 2, "x")])
        orc.append([b, len(ids), best_a, fmt(tot_off / fixed[best_a], 2, "x"), fmt(tot_off / dom_router, 2, "x"),
                    fmt(tot_off / oracle, 2, "x"), fmt(100 * (fixed[best_a] / oracle - 1), 1, "%"),
                    "; ".join(f"{a} {n}" for a, n in winners.most_common(4))])
    P("Caveats: the oracle picks each prompt's minimum, so per-prompt timing noise inflates it a little; "
      "the domain router is chosen and scored on the same few prompts per domain (1 to 19).\n")
    P(md_table(["bucket", "prompts", "best fixed arm", "best fixed", "domain router", "per-prompt oracle",
                "oracle over best fixed", "per-prompt winners (top 4)"], orc))
    P("\nBy domain (speedup of the domain's best arm, and of the bucket's best fixed arm, on that domain's prompts):\n")
    P(md_table(["bucket", "domain", "prompts", "domain's best arm", "its speedup", "bucket's best fixed arm"], dom_tab))

    # ---------------------------------------------------------------- acc and output length
    P("\n## 7. Per-request acceptance (acc cell) and output length\n")
    acc = []
    for b in BUCKETS:
        for r in sorted((r for r in allrows if r["_cell"] == "acc" and r["_bucket"] == b and r["rung"] != "off"), key=lambda r: arm_key(arm(r))):
            vals = []
            for q in r["_perreq"]:
                sm = q.get("spec_decode_metrics") or {}
                acc_steps = sm.get("per_step_accepted")
                if acc_steps:   # vLLM 0.33.0 "detailed": accepted tokens per verify step
                    vals.append(sum(acc_steps) / len(acc_steps) + 1)
            if vals:
                vals.sort()
                acc.append([b, arm(r), len(vals), fmt(vals[len(vals) // 10]), fmt(st.median(vals)), fmt(vals[-1 - len(vals) // 10])])
    P("Per-prompt tau (10th percentile, median, 90th percentile):\n")
    P(md_table(["bucket", "arm", "prompts", "p10", "median", "p90"], acc) if acc else
      "_The acc rows carry no per-request acceptance fields this script recognises; see the raw perreq files._")
    ol = []
    for t in ("t64", "t512"):
        rows = [r for r in allrows if r["_dir"] == f"gh200v2_outlen_{t}"]
        o = [r for r in rows if r["rung"] == "off"]
        for r in rows:
            if r["rung"] != "off" and o:
                ol.append(["32K", r.get("max_tokens"), arm(r), fmt(o[0]["elapsed_s"] / r["elapsed_s"], 2, "x"), fmt(tau(r))])
    if ol:
        P("\nOutput length at 32K (10 prompts):\n")
        P(md_table(["bucket", "output tokens", "arm", "speedup", "tau"], ol))

    task_section(data, P)


def task_section(data, P=print):
    """Section 8: task-type cells (gh200v2_t<task>_<B>, from the task-<B> bundles)."""
    tasks = ["code", "summ", "fewshot", "mdqa"]
    cells = {}
    for d, m, rows in data:
        c = m["cell"]
        if not (c.startswith("t") and c[1:] in tasks):
            continue
        for r in rows:
            if r["rung"] == "off":
                continue
            o = off_for(r, rows)
            cells.setdefault((c[1:], m["bucket"]), {})[arm(r)] = (o["elapsed_s"] / r["elapsed_s"] if o else None, tau(r))
    P("\n## 8. Task type (code, summarization, few-shot, multi-document QA)\n")
    if not cells:
        P("_No task-type results yet (task-2K / task-8K pieces)._")
        return
    P("Each arm against the off arm of its own piece, every request run to 256 tokens. "
      "The `mc` row is LongBench v2 multiple choice, the core cells' arms, for comparison.\n")
    arms = ["ngram_gpu k=5", "ngram_gpu k=11", "dflash k=7", "dflash k=15"]
    core = {}
    for d, m, rows in data:
        if m["cell"] == "ksweep":
            for r in rows:
                if r["rung"] != "off" and arm(r) in arms:
                    o = off_for(r, rows)
                    core.setdefault(m["bucket"], {})[arm(r)] = (o["elapsed_s"] / r["elapsed_s"] if o else None, tau(r))
    rows_out = []
    for b in ("2K", "8K"):
        for t in tasks + ["mc"]:
            v = core.get(b, {}) if t == "mc" else cells.get((t, b))
            if not v:
                continue
            best = max((a for a in arms if v.get(a, (None,))[0]), key=lambda a: v[a][0], default=None)
            bn = max((a for a in arms[:2] if v.get(a, (None,))[0]), key=lambda a: v[a][0], default=None)
            bd = max((a for a in arms[2:] if v.get(a, (None,))[0]), key=lambda a: v[a][0], default=None)
            rows_out.append([b, t] + [f"{fmt(v.get(a, (None, None))[0], 2, 'x')} ({fmt(v.get(a, (None, None))[1])})" for a in arms]
                            + [best or "-", fmt(100 * (v[bd][0] / v[bn][0] - 1), 0, "%") if bn and bd else "-"])
    P(md_table(["bucket", "task"] + [f"{a} (tau)" for a in arms] + ["best arm", "best DFlash over best n-gram"], rows_out))


